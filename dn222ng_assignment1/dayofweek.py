day = str(input("What day would you like to translate? "))

if day == "Monday":
    print("Måndag")
elif day == "Tuesday":
    print("Tisdag")
elif day == "Wednesday":
    print("Onsdag")
elif day == "Thursday":
    print("Torsdag")
elif day == "Friday":
    print("Fredag")
elif day == "Saturday":
    print("Lördag")
elif day == "Sunday":
    print("Söndag")
else:
    print("Wrong input")